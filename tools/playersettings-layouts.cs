#:property ManagePackageVersionsCentrally=false
#:property PublishAot=false

// Writes src/Lustral.Core/GameData/PlayerSettingsLayouts.txt, which describes how to read the game's company name,
// product name and version (PlayerSettings' companyName, productName and bundleVersion) from globalgamemanagers for each
// Unity version in AssetRipper's type tree package, without shipping the package (player builds do not include type
// trees).
//
//   1. Download the latest package: https://nightly.link/AssetRipper/Tpk/workflows/type_tree_tpk/master/lz4_file.zip
//      (linked from AssetRipper/Tpk's README). If nightly.link cannot find the artifact, use
//      https://nightly.link/AssetRipper/Tpk/actions/runs/<run id>/lz4_file.zip with the latest "Type Tree Tpk" run.
//   2. dotnet run tools/playersettings-layouts.cs -- <lz4.tpk>
//
// Regenerate the file when new Unity versions are released. For versions it does not list, Lustral cannot read the
// game's version from its files and uses the version reported by the running game instead.
using System.Globalization;
using System.Text;
using AssetsTools.NET;
using AssetsTools.NET.Extra;

const int PlayerSettingsClassId = 129;
const uint AlignFlag = 0x4000;
var oldest = new UnityVersion("2017.1.0a1");

if (args.Length < 1)
{
    Console.Error.WriteLine("Usage: dotnet run tools/playersettings-layouts.cs -- <type tree package (.tpk)> [output]");
    return 1;
}
var output = args.Length > 1 ? args[1] : Path.Combine(Path.GetDirectoryName(Path.GetFullPath(ThisFile()))!, "..", "src", "Lustral.Core", "GameData", "PlayerSettingsLayouts.txt");

var package = new ClassPackageFile();
package.Read(args[0]);
var tree = package.TpkTypeTree;
string Text(ushort index) => tree.StringTable.GetString(index);
var playerSettings = tree.ClassInformation.Single(c => c.ClassId == PlayerSettingsClassId);

var layouts = new List<string>();
var versions = new List<string>();
foreach (var (version, type) in playerSettings.Classes)
{
    if (version.ToUInt64() < oldest.ToUInt64() || type is null || type.ReleaseRootNode == ushort.MaxValue)
        continue;
    var root = tree.Nodes[type.ReleaseRootNode];
    var tokens = new List<string>();
    var captured = 0;
    foreach (var child in root.SubNodes)
    {
        var name = Text(tree.Nodes[child].FieldName);
        Emit(child, name switch { "companyName" => "company", "productName" => "product", "bundleVersion" => "version", _ => null }, tokens);
        if (name is "companyName" or "productName" or "bundleVersion")
            captured++;
        if (name == "bundleVersion")
            break;
    }
    if (captured != 3)
    {
        Console.WriteLine($"{version}: PlayerSettings lacks companyName, productName or bundleVersion; skipped");
        continue;
    }

    var line = string.Join(" ", Merge(tokens));
    var index = layouts.IndexOf(line);
    if (index < 0)
    {
        index = layouts.Count;
        layouts.Add(line);
    }
    versions.Add($"V {version} {Convert.ToHexString(TypeHash(type.ReleaseRootNode)).ToLowerInvariant()} {index}");
}

var text = new StringBuilder();
text.Append($"""
    # PlayerSettings up to bundleVersion, for reading the game's company, product name and version from globalgamemanagers.
    # Generated by tools/playersettings-layouts.cs from AssetRipper's type tree package (built {tree.CreationTime.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)}); don't edit.
    #
    # L <id> <tokens>       a layout. Tokens, read in order: a number skips that many bytes; ! aligns to 4 bytes from the object's
    #                       start; [ ... ] reads an int32 count and the tokens inside that many times; s:<name> reads a string
    #                       (int32 length, UTF-8 bytes) and keeps it as company, product or version.
    # V <unity> <hash> <id> the first Unity version whose PlayerSettings type tree hashes to <hash> (the MD4 that serialized
    #                       files store for each type), and the layout it has. A version keeps its line's layout until the next line.

    """);
for (var i = 0; i < layouts.Count; i++)
    text.Append($"L {i} {layouts[i]}\n");
foreach (var line in versions)
    text.Append(line).Append('\n');
File.WriteAllText(output, text.ToString().Replace("\r\n", "\n"));
Console.WriteLine($"{versions.Count} versions ({versions[0].Split(' ')[1]} to {versions[^1].Split(' ')[1]}), {layouts.Count} layouts, {new FileInfo(output).Length / 1024.0:0.0} KB -> {Path.GetFullPath(output)}");
return 0;

// Flattens a field into tokens: leaves become byte counts, arrays become [ element ], and aligned fields are followed by !.
void Emit(ushort index, string? capture, List<string> tokens)
{
    var node = tree.Nodes[index];
    var typeName = Text(node.TypeName);
    if (capture is not null)
    {
        if (typeName != "string")
            throw new InvalidOperationException($"{Text(node.FieldName)} is a {typeName}, not a string");
        tokens.Add("s:" + capture);
        if ((node.MetaFlag & AlignFlag) != 0 || node.SubNodes.Any(c => (tree.Nodes[c].MetaFlag & AlignFlag) != 0))
            tokens.Add("!");
        return;
    }

    if ((node.TypeFlags & 1) != 0 || typeName == "TypelessData")
    {
        // Array: an int32 size, followed by the elements.
        if (node.SubNodes.Length != 2)
            throw new InvalidOperationException($"array {Text(node.FieldName)} has {node.SubNodes.Length} children");
        tokens.Add("[");
        Emit(node.SubNodes[1], null, tokens);
        tokens.Add("]");
    }
    else if (node.SubNodes.Length == 0)
    {
        if (node.ByteSize <= 0)
            throw new InvalidOperationException($"leaf {typeName} {Text(node.FieldName)} has size {node.ByteSize}");
        tokens.Add(node.ByteSize.ToString(CultureInfo.InvariantCulture));
    }
    else
    {
        foreach (var child in node.SubNodes)
            Emit(child, null, tokens);
    }
    if ((node.MetaFlag & AlignFlag) != 0)
        tokens.Add("!");
}

// Sums consecutive byte counts and removes repeated alignments, so that "4 4 1 ! !" becomes "9 !".
static IEnumerable<string> Merge(List<string> tokens)
{
    var bytes = 0;
    string? previous = null;
    foreach (var token in tokens)
    {
        if (int.TryParse(token, NumberStyles.None, CultureInfo.InvariantCulture, out var count))
        {
            bytes += count;
            continue;
        }
        if (bytes > 0)
        {
            yield return previous = bytes.ToString(CultureInfo.InvariantCulture);
            bytes = 0;
        }
        if (token == "!" && previous == "!")
            continue;
        yield return previous = token;
    }
    if (bytes > 0)
        yield return bytes.ToString(CultureInfo.InvariantCulture);
}

// Unity's type hash: MD4 over each node, depth first (type name, field name, then int32 byte size, type flags, version
// and alignment flag). Matches the hashes in games' globalgamemanagers files.
byte[] TypeHash(ushort rootIndex)
{
    using var stream = new MemoryStream();
    using var writer = new BinaryWriter(stream);
    void Write(ushort index)
    {
        var node = tree.Nodes[index];
        writer.Write(Encoding.UTF8.GetBytes(Text(node.TypeName)));
        writer.Write(Encoding.UTF8.GetBytes(Text(node.FieldName)));
        writer.Write(node.ByteSize);
        writer.Write((int)node.TypeFlags);
        writer.Write((int)node.Version);
        writer.Write(node.MetaFlag & AlignFlag);
        foreach (var child in node.SubNodes)
            Write(child);
    }
    Write(rootIndex);
    writer.Flush();
    return Md4(stream.ToArray());
}

static byte[] Md4(byte[] input)
{
    uint a = 0x67452301, b = 0xefcdab89, c = 0x98badcfe, d = 0x10325476;
    var padded = new byte[((input.Length + 8) / 64 + 1) * 64];
    input.CopyTo(padded, 0);
    padded[input.Length] = 0x80;
    BitConverter.GetBytes((ulong)input.Length * 8).CopyTo(padded, padded.Length - 8);
    int[] shifts1 = [3, 7, 11, 19], shifts2 = [3, 5, 9, 13], shifts3 = [3, 9, 11, 15];
    int[] order2 = [0, 4, 8, 12, 1, 5, 9, 13, 2, 6, 10, 14, 3, 7, 11, 15], order3 = [0, 8, 4, 12, 2, 10, 6, 14, 1, 9, 5, 13, 3, 11, 7, 15];
    var x = new uint[16];
    for (var offset = 0; offset < padded.Length; offset += 64)
    {
        for (var j = 0; j < 16; j++)
            x[j] = BitConverter.ToUInt32(padded, offset + j * 4);
        uint aa = a, bb = b, cc = c, dd = d;
        for (var k = 0; k < 48; k++)
        {
            var (f, word, shift) = (k / 16) switch
            {
                0 => ((b & c) | (~b & d), x[k], shifts1[k % 4]),
                1 => (((b & c) | (b & d) | (c & d)) + 0x5a827999, x[order2[k - 16]], shifts2[k % 4]),
                _ => ((b ^ c ^ d) + 0x6ed9eba1, x[order3[k - 32]], shifts3[k % 4]),
            };
            var t = a + f + word;
            (a, d, c, b) = (d, c, b, (t << shift) | (t >> (32 - shift)));
        }
        a += aa; b += bb; c += cc; d += dd;
    }
    var hash = new byte[16];
    BitConverter.GetBytes(a).CopyTo(hash, 0);
    BitConverter.GetBytes(b).CopyTo(hash, 4);
    BitConverter.GetBytes(c).CopyTo(hash, 8);
    BitConverter.GetBytes(d).CopyTo(hash, 12);
    return hash;
}

static string ThisFile([System.Runtime.CompilerServices.CallerFilePath] string path = "") => path;

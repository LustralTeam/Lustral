using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Lustral.Analyzers;

/// <summary>
/// Checks HarmonyX patch classes as Harmony resolves them at runtime, so that errors are reported at build time instead
/// of in the game: the target method must exist (including in base types, as with AccessTools), must not be an ambiguous
/// overload, and every parameter of a prefix, postfix or finalizer must be a target parameter or one of Harmony's
/// injections (<c>__instance</c>, <c>__result</c>, <c>___field</c>, ...). Classes that select targets in code
/// (TargetMethod, TargetMethods) or by type name are not checked.
/// </summary>
/// <remarks>
/// The compiler imports only the public and protected members of referenced assemblies, and private game methods are
/// commonly patched. Targets in such assemblies, such as a Mono game's, are therefore resolved in a copy of the
/// compilation that imports all members. Assemblies generated by Il2CppInterop need no copy, as all their members are
/// public.
/// </remarks>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class HarmonyPatchAnalyzer : DiagnosticAnalyzer
{
    // Harmony's MethodType values.
    private const int Normal = 0, Getter = 1, Setter = 2, Constructor = 3, StaticConstructor = 4;

    private static readonly ImmutableHashSet<string> PatchMethodNames = ["Prefix", "Postfix", "Finalizer"];
    private static readonly ImmutableHashSet<string> PatchAttributeNames = ["HarmonyPrefix", "HarmonyPostfix", "HarmonyFinalizer"];
    private static readonly ImmutableHashSet<string> InjectedNames =
        ["__instance", "__result", "__resultRef", "__state", "__args", "__originalMethod", "__runOriginal", "__exception"];

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics { get; } =
        [Diagnostics.PatchTargetNotFound, Diagnostics.PatchTargetAmbiguous, Diagnostics.PatchParameterUnknown];

    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(start =>
        {
            var patchAttribute = start.Compilation.GetTypeByMetadataName("HarmonyLib.HarmonyPatch");
            if (patchAttribute is null)
                return;
            var argumentAttribute = start.Compilation.GetTypeByMetadataName("HarmonyLib.HarmonyArgument");
            var allMembers = new Lazy<Compilation>(() =>
                start.Compilation.WithOptions(start.Compilation.Options.WithMetadataImportOptions(MetadataImportOptions.All)));
            start.RegisterSymbolAction(symbol => AnalyzeClass(symbol, patchAttribute, argumentAttribute, allMembers), SymbolKind.NamedType);
        });
    }

    private static void AnalyzeClass(SymbolAnalysisContext context, INamedTypeSymbol patchAttribute, INamedTypeSymbol? argumentAttribute, Lazy<Compilation> allMembers)
    {
        var patchClass = (INamedTypeSymbol)context.Symbol;
        var classAttributes = PatchAttributes(patchClass, patchAttribute);
        var methods = patchClass.GetMembers().OfType<IMethodSymbol>().ToList();
        if (classAttributes.Count == 0 && !methods.Any(m => PatchAttributes(m, patchAttribute).Count > 0))
            return;
        // Targets chosen in code.
        if (methods.Any(m => m.Name is "TargetMethod" or "TargetMethods"))
            return;

        var classTarget = Merge(new Target(), classAttributes);
        foreach (var method in methods.Where(m => IsPatchMethod(m)))
        {
            var methodAttributes = PatchAttributes(method, patchAttribute);
            var target = Merge(classTarget, methodAttributes);
            if (target.Unresolvable || target.Type is null)
                continue;
            var location = (methodAttributes.LastOrDefault() ?? classAttributes.LastOrDefault())?.ApplicationSyntaxReference?.GetSyntax(context.CancellationToken).GetLocation()
                           ?? method.Locations.FirstOrDefault();

            var visible = AllMembersVisible(context.Compilation, target.Type);
            if (!visible && WithAllMembers(allMembers.Value, context.Compilation, target.Type) is { } type)
                (target, visible) = (target with { Type = type }, true);
            var original = Resolve(context, target, location, visible);
            if (original is not null)
                CheckParameters(context, method, original, target.Type, argumentAttribute, visible);
        }
    }

    private static bool IsPatchMethod(IMethodSymbol method) =>
        method.MethodKind == MethodKind.Ordinary &&
        (PatchMethodNames.Contains(method.Name) || method.GetAttributes().Any(a => a.AttributeClass is { } c && PatchAttributeNames.Contains(c.Name) && c.ContainingNamespace.ToDisplayString() == "HarmonyLib"));

    private static List<AttributeData> PatchAttributes(ISymbol symbol, INamedTypeSymbol patchAttribute) =>
        symbol.GetAttributes().Where(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, patchAttribute)).ToList();

    private sealed record Target
    {
        public INamedTypeSymbol? Type { get; init; }
        public string? MethodName { get; init; }
        public int MethodType { get; init; }
        public ImmutableArray<ITypeSymbol>? ArgumentTypes { get; init; }
        /// <summary>A type specified by name, or a ref/out/pointer variation, which is left to Harmony.</summary>
        public bool Unresolvable { get; init; }
    }

    // Later attributes refine earlier ones, as Harmony merges class and method attributes.
    private static Target Merge(Target target, IEnumerable<AttributeData> attributes)
    {
        foreach (var attribute in attributes)
        {
            var args = attribute.ConstructorArguments;
            if (args.Length > 0 && args[0].Kind == TypedConstantKind.Primitive && args[0].Value is string && args.Length >= 2 &&
                args[1].Kind == TypedConstantKind.Primitive && args[1].Value is string)
            {
                // HarmonyPatch(string typeName, string methodName, ...): the type is known only at runtime.
                target = target with { Unresolvable = true };
                continue;
            }

            foreach (var argument in args)
            {
                switch (argument.Kind)
                {
                    case TypedConstantKind.Type when argument.Value is INamedTypeSymbol type:
                        target = target with { Type = type };
                        break;
                    case TypedConstantKind.Primitive when argument.Value is string name:
                        target = target with { MethodName = name };
                        break;
                    case TypedConstantKind.Enum when argument.Type?.Name == "MethodType" && argument.Value is int methodType:
                        target = target with { MethodType = methodType };
                        break;
                    case TypedConstantKind.Array when argument.Type is IArrayTypeSymbol { ElementType.Name: "Type" }:
                        target = target with { ArgumentTypes = argument.Values.Select(v => v.Value).OfType<ITypeSymbol>().ToImmutableArray() };
                        break;
                    case TypedConstantKind.Array when argument.Type is IArrayTypeSymbol { ElementType.Name: "ArgumentType" }:
                        if (argument.Values.Any(v => v.Value is int variation && variation != 0))
                            target = target with { Unresolvable = true };
                        break;
                }
            }
        }
        return target;
    }

    private static IMethodSymbol? Resolve(SymbolAnalysisContext context, Target target, Location? location, bool visible)
    {
        var type = target.Type!;
        var display = type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
        switch (target.MethodType)
        {
            case Normal:
            {
                if (target.MethodName is null)
                    return null; // Reported by Harmony; incomplete attributes are also common while editing.
                var candidates = Hierarchy(type).SelectMany(t => t.GetMembers(target.MethodName)).OfType<IMethodSymbol>()
                    .Where(m => m.MethodKind == MethodKind.Ordinary).ToList();
                return Pick(context, candidates, target, location, $"{display}.{target.MethodName}", display, visible);
            }
            case Getter or Setter:
            {
                var name = target.MethodName ?? "Item";
                var property = Hierarchy(type).SelectMany(t => t.GetMembers(name)).OfType<IPropertySymbol>().FirstOrDefault();
                var accessor = target.MethodType == Getter ? property?.GetMethod : property?.SetMethod;
                if (accessor is null && visible)
                    Report(context, Diagnostics.PatchTargetNotFound, location,
                        property is null ? $"{display} has no property {name}" : $"{display}.{name} has no {(target.MethodType == Getter ? "getter" : "setter")}");
                return accessor;
            }
            case Constructor:
                // A struct's implicit parameterless constructor is not a method that Harmony can patch.
                return Pick(context, type.InstanceConstructors.Where(c => !(c.IsImplicitlyDeclared && type.IsValueType)).ToList(), target, location, $"{display}'s constructor", display, visible);
            case StaticConstructor:
                if (type.StaticConstructors.IsEmpty && visible)
                    Report(context, Diagnostics.PatchTargetNotFound, location, $"{display} has no static constructor");
                return type.StaticConstructors.FirstOrDefault();
            default:
                return null; // Enumerator, Async: Harmony locates the generated method.
        }
    }

    private static IMethodSymbol? Pick(SymbolAnalysisContext context, List<IMethodSymbol> candidates, Target target, Location? location, string what, string typeDisplay, bool visible)
    {
        if (candidates.Count == 0)
        {
            if (visible)
                Report(context, Diagnostics.PatchTargetNotFound, location, $"{what} does not exist");
            return null;
        }

        if (target.ArgumentTypes is { } argumentTypes)
        {
            var match = candidates.FirstOrDefault(m => m.Parameters.Length == argumentTypes.Length &&
                m.Parameters.Zip(argumentTypes, (p, t) => SameType(p.Type, t)).All(same => same));
            if (match is null && visible)
            {
                var wanted = string.Join(", ", argumentTypes.Select(t => t.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)));
                Report(context, Diagnostics.PatchTargetNotFound, location, $"{what} has no overload taking ({wanted})");
            }
            return match;
        }

        // Harmony selects the most derived declaration; overrides of a virtual method are not overloads.
        var distinct = candidates.GroupBy(m => string.Join(",", m.Parameters.Select(p => p.Type.ToDisplayString()))).Select(g => g.First()).ToList();
        if (distinct.Count > 1)
        {
            Report(context, Diagnostics.PatchTargetAmbiguous, location, what, distinct.Count, typeDisplay, distinct[0].Name);
            return null;
        }
        return distinct[0];
    }

    private static void CheckParameters(SymbolAnalysisContext context, IMethodSymbol patch, IMethodSymbol original, INamedTypeSymbol targetType, INamedTypeSymbol? argumentAttribute, bool visible)
    {
        var targetDisplay = $"{targetType.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)}.{(original.MethodKind == MethodKind.Constructor ? "ctor" : original.Name)}";
        var originalNames = original.Parameters.Select(p => p.Name).ToImmutableHashSet();
        foreach (var parameter in patch.Parameters)
        {
            var name = parameter.Name;
            // [HarmonyArgument] renames a parameter; Harmony validates these itself.
            if (argumentAttribute is not null && parameter.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, argumentAttribute)))
                continue;
            if (originalNames.Contains(name))
                continue;
            if (name == "__result" && original.ReturnsVoid && original.MethodKind == MethodKind.Ordinary)
            {
                Report(context, Diagnostics.PatchParameterUnknown, parameter.Locations.FirstOrDefault(), $"__result: {targetDisplay} returns nothing");
                continue;
            }
            if (name == "__instance" && original.IsStatic)
            {
                Report(context, Diagnostics.PatchParameterUnknown, parameter.Locations.FirstOrDefault(), $"__instance: {targetDisplay} is static and has no instance");
                continue;
            }
            if (InjectedNames.Contains(name))
                continue;
            if (name.StartsWith("__", StringComparison.Ordinal) && int.TryParse(name.Substring(2), out var index))
            {
                if (index >= original.Parameters.Length)
                    Report(context, Diagnostics.PatchParameterUnknown, parameter.Locations.FirstOrDefault(), $"{name}: {targetDisplay} has {original.Parameters.Length} parameter(s), counted from __0");
                continue;
            }
            if (name.StartsWith("___", StringComparison.Ordinal))
            {
                var field = name.Substring(3);
                if (visible && !Hierarchy(targetType).Any(t => t.GetMembers(field).OfType<IFieldSymbol>().Any()))
                    Report(context, Diagnostics.PatchParameterUnknown, parameter.Locations.FirstOrDefault(), $"{name}: {targetType.Name} has no field {field}");
                continue;
            }

            Report(context, Diagnostics.PatchParameterUnknown, parameter.Locations.FirstOrDefault(), original.Parameters.IsEmpty
                ? $"{name}: {targetDisplay} takes no parameters, so a patch can only use injections such as __instance or __result"
                : $"{name}: {targetDisplay} has parameters {string.Join(", ", original.Parameters.Select(p => p.Name))}; use one of these names, __0 for the first parameter, or an injection such as __instance or __result");
        }
    }

    // The type as seen by the compilation that imports all members, or null if it cannot be found there (a constructed
    // generic type, for example).
    private static INamedTypeSymbol? WithAllMembers(Compilation allMembers, Compilation compilation, INamedTypeSymbol type)
    {
        if (!SymbolEqualityComparer.Default.Equals(type, type.OriginalDefinition) || compilation.GetMetadataReference(type.ContainingAssembly) is not { } reference)
            return null;
        return (allMembers.GetAssemblyOrModuleSymbol(reference) as IAssemblySymbol)?.GetTypeByMetadataName(MetadataName(type));
    }

    private static string MetadataName(INamedTypeSymbol type) =>
        type.ContainingType is { } outer ? $"{MetadataName(outer)}+{type.MetadataName}"
        : type.ContainingNamespace.IsGlobalNamespace ? type.MetadataName
        : $"{type.ContainingNamespace.ToDisplayString()}.{type.MetadataName}";

    // Types from the two compilations are different symbols, so they are compared by name.
    private static bool SameType(ITypeSymbol a, ITypeSymbol b) =>
        SymbolEqualityComparer.Default.Equals(a, b) ||
        a.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == b.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    // True if every type in the hierarchy is declared in source or generated by Il2CppInterop (System.Object's private
    // members are irrelevant), or if the compilation imports private members.
    private static bool AllMembersVisible(Compilation compilation, INamedTypeSymbol type) =>
        compilation.Options.MetadataImportOptions == MetadataImportOptions.All ||
        Hierarchy(type).All(t => t.SpecialType == SpecialType.System_Object || t.Locations.Any(l => l.IsInSource) || IsInterop(t.ContainingAssembly));

    // Il2CppInterop's assemblies and the assemblies it generated, which reference it.
    private static bool IsInterop(IAssemblySymbol? assembly) =>
        assembly is not null &&
        (assembly.Name.StartsWith("Il2CppInterop.", StringComparison.Ordinal) ||
         assembly.Modules.Any(m => m.ReferencedAssemblies.Any(r => r.Name.StartsWith("Il2CppInterop.", StringComparison.Ordinal))));

    private static IEnumerable<INamedTypeSymbol> Hierarchy(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.BaseType)
            yield return current;
    }

    private static void Report(SymbolAnalysisContext context, DiagnosticDescriptor descriptor, Location? location, params object[] args) =>
        context.ReportDiagnostic(Diagnostic.Create(descriptor, location, args));
}

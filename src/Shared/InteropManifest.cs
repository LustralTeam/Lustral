using System.IO.Hashing;
using System.Text.Json;

namespace Lustral.Interop;

/// <summary>
/// <c>Lustral/interop/interop.json</c>: the inputs from which the interop assemblies were generated. The cache is up to
/// date as long as the game binaries, the Il2CppInterop version and the format all match.
/// </summary>
internal sealed class InteropManifest
{
    public const string FileName = "interop.json";

    /// <summary>Incremented when the structure of the Generator's output changes, so that existing caches are regenerated.
    /// 2: EnumBaseTypeFix. 3: ConstraintIndicesFix. 4: ReadyToRun. 5: unstripped by default, from Lustral's Unity libraries.
    /// 6: TypeSizeFix. 7: Cpp2IL 1.0.9.</summary>
    public const int CurrentFormat = 7;

    /// <summary>The stale reason used when only unstripping needs to be retried.</summary>
    public const string UnstripRetryReason = "unstripping was not possible last time; retrying";

    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };

    public int Format { get; set; } = CurrentFormat;
    public required string UnityVersion { get; set; }
    public required string Il2CppInteropVersion { get; set; }
    public required string GameAssemblyHash { get; set; }
    public required string MetadataHash { get; set; }
    public bool Unstripped { get; set; }

    /// <summary>The source of the Unity libraries used for unstripping.</summary>
    public string? UnityLibraries { get; set; }

    /// <summary>The reason the assemblies were not unstripped, if unstripping was expected.</summary>
    public string? UnstripProblem { get; set; }

    /// <summary>The time at which to retry unstripping after a temporary problem (offline, or libraries not yet published).</summary>
    public DateTime? UnstripRetryUtc { get; set; }
    public bool ReadyToRun { get; set; }
    public DateTime CreatedUtc { get; set; }

    public static InteropManifest? TryRead(string interopDirectory)
    {
        var path = Path.Combine(interopDirectory, FileName);
        if (!File.Exists(path))
            return null;
        try
        {
            return JsonSerializer.Deserialize<InteropManifest>(File.ReadAllText(path), JsonOptions);
        }
        catch (JsonException)
        {
            return null;
        }
    }

    public void Write(string interopDirectory) =>
        File.WriteAllText(Path.Combine(interopDirectory, FileName), JsonSerializer.Serialize(this, JsonOptions));

    /// <summary>Returns why the cache is stale, or null if it matches this game and Il2CppInterop version.</summary>
    public string? StaleReason(GameLayout game, string il2CppInteropVersion)
    {
        if (Format != CurrentFormat)
            return $"cache format {Format}, expected {CurrentFormat}";
        if (Il2CppInteropVersion != il2CppInteropVersion)
            return $"generated by Il2CppInterop {Il2CppInteropVersion}, running {il2CppInteropVersion}";
        if (GameAssemblyHash != HashFile(game.GameAssemblyPath))
            return "GameAssembly.dll has changed (likely a game update)";
        if (MetadataHash != HashFile(game.MetadataPath))
            return "global-metadata.dat has changed (likely a game update)";
        if (UnstripRetryUtc is { } retry && DateTime.UtcNow >= retry)
            return UnstripRetryReason;
        return null;
    }

    /// <summary>The Il2CppInterop package version used by this build, without the commit suffix.</summary>
    public static string CurrentIl2CppInteropVersion { get; } = ReadIl2CppInteropVersion();

    private static string ReadIl2CppInteropVersion()
    {
        var assembly = typeof(Il2CppInterop.Runtime.Startup.Il2CppInteropRuntime).Assembly;
        var informational = assembly.GetCustomAttributes(typeof(System.Reflection.AssemblyInformationalVersionAttribute), false)
            .OfType<System.Reflection.AssemblyInformationalVersionAttribute>()
            .FirstOrDefault()?.InformationalVersion;
        return informational?.Split('+')[0] ?? assembly.GetName().Version?.ToString() ?? "unknown";
    }

    /// <summary>The XxHash128 hash of the file, as lowercase hexadecimal. Takes about 100 ms for a 70 MB GameAssembly.</summary>
    public static string HashFile(string path)
    {
        using var stream = File.OpenRead(path);
        var hash = new XxHash128();
        hash.Append(stream);
        return Convert.ToHexStringLower(hash.GetCurrentHash());
    }
}

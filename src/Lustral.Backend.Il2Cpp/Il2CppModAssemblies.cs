using System.Reflection;
using System.Runtime.CompilerServices;
using Il2CppInterop.Common.Attributes;
using Lustral.Core.Loading;
using Lustral.Core.Mods;

namespace Lustral.Backend.Il2Cpp;

/// <summary>
/// Registers a mod's injected IL2CPP classes (Il2CppInterop's <c>[InjectedType]</c>) when its assembly loads, before any
/// of the mod's code runs. Il2CppInterop registers a class when managed code first uses it, which is too late if the game
/// creates an instance first (for example, from a prefab or asset bundle containing the mod's component), and turns a
/// registration error into a type initializer failure in whatever code accessed the type. Registering here instead stops
/// the affected mod and reports the reason.
/// </summary>
internal sealed class Il2CppModAssemblies(IModAssemblyLoader inner, ILog log) : IModAssemblyLoader
{
    public void Register(DiscoveredMod mod) => inner.Register(mod);

    public Assembly Load(DiscoveredMod mod, string path)
    {
        var assembly = inner.Load(mod, path);
        var injected = InjectedTypes(assembly);
        foreach (var type in injected)
        {
            try
            {
                // The static constructor generated by the source generator registers the class (through its Il2CppInternals).
                RuntimeHelpers.RunClassConstructor(type.TypeHandle);
            }
            catch (TypeInitializationException e)
            {
                throw new InvalidOperationException($"Could not register {type.FullName} with IL2CPP: {(e.InnerException ?? e).Message}", e.InnerException ?? e);
            }
        }
        if (injected.Count > 0)
            log.Debug($"Registered {mod.Id}'s IL2CPP classes: {string.Join(", ", injected.Select(t => t.Name))}");
        return assembly;
    }

    // [InjectedType] classes, which the source generator marks with [Il2CppType], with base classes first.
    private static List<Type> InjectedTypes(Assembly assembly) =>
        Loadable(assembly)
            .Where(t => t is { IsClass: true, ContainsGenericParameters: false } && t.IsDefined(typeof(Il2CppTypeAttribute), inherit: false))
            .OrderBy(Depth)
            .ToList();

    private static int Depth(Type type)
    {
        var depth = 0;
        for (var current = type.BaseType; current is not null; current = current.BaseType)
            depth++;
        return depth;
    }

    private static IEnumerable<Type> Loadable(Assembly assembly)
    {
        try
        {
            return assembly.GetTypes();
        }
        catch (ReflectionTypeLoadException e)
        {
            return e.Types.OfType<Type>();
        }
    }
}

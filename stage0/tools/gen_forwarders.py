r"""Generates stage0/src/forwarders_<name>.h: linker pragmas forwarding every export of a System32 DLL.

Usage: python stage0/tools/gen_forwarders.py winhttp

Forwarders point at \\.\GLOBALROOT\SystemRoot\System32\<name>.dll, so the proxy needs no code per export and
never loads the real DLL itself; the Windows loader resolves each forwarder when the game imports it.
"""
import os
import struct
import sys

name = sys.argv[1]
path = os.path.join(os.environ["SystemRoot"], "System32", name + ".dll")
data = open(path, "rb").read()

pe = struct.unpack_from("<I", data, 0x3C)[0]
assert data[pe:pe + 4] == b"PE\0\0"
machine = struct.unpack_from("<H", data, pe + 4)[0]
assert machine == 0x8664, "expected an x64 DLL"
sections_count = struct.unpack_from("<H", data, pe + 6)[0]
optional_size = struct.unpack_from("<H", data, pe + 20)[0]
optional = pe + 24
export_rva, export_size = struct.unpack_from("<II", data, optional + 112)  # PE32+ data directory 0
section_table = optional + optional_size
sections = [struct.unpack_from("<8sIIII", data, section_table + i * 40) for i in range(sections_count)]


def offset(rva):
    for _, vsize, vaddr, rawsize, rawptr in sections:
        if vaddr <= rva < vaddr + max(vsize, rawsize):
            return rva - vaddr + rawptr
    raise ValueError(hex(rva))


def cstring(rva):
    start = offset(rva)
    return data[start:data.index(b"\0", start)].decode("ascii")


e = offset(export_rva)
base, functions_count, names_count, functions_rva, names_rva, ordinals_rva = struct.unpack_from("<IIIIII", data, e + 16)
named = {}
for i in range(names_count):
    name_rva = struct.unpack_from("<I", data, offset(names_rva) + i * 4)[0]
    index = struct.unpack_from("<H", data, offset(ordinals_rva) + i * 2)[0]
    named[index] = cstring(name_rva)

# The real path is \\.\GLOBALROOT\SystemRoot\System32\<name>.dll; inside the C string literal every backslash doubles.
real_dll = "\\\\.\\GLOBALROOT\\SystemRoot\\System32\\" + name + ".dll"
target = real_dll.replace("\\", "\\\\")
lines = [
    "// Generated by stage0/tools/gen_forwarders.py from %s. Do not edit." % path,
    "// Every export forwards to the real DLL, with the same name and ordinal.",
    "#pragma once",
    "",
]
count = 0
for index in range(functions_count):
    if struct.unpack_from("<I", data, offset(functions_rva) + index * 4)[0] == 0:
        continue  # unused ordinal slot
    ordinal = base + index
    if index in named:
        export = named[index]
        lines.append('#pragma comment(linker, "/export:%s=%s.%s,@%d")' % (export, target, export, ordinal))
    else:
        lines.append('#pragma comment(linker, "/export:__ordinal%d=%s.#%d,@%d,NONAME")' % (ordinal, target, ordinal, ordinal))
    count += 1

out = os.path.join(os.path.dirname(__file__), "..", "src", "forwarders_%s.h" % name)
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote %d forwarders to %s" % (count, os.path.normpath(out)))
